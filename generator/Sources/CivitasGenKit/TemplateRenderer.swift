import Foundation

/// Expands the synthetic domain template into source files, keyed by source folder like `Domains/<Name>/API`.
public struct TemplateRenderer {
    public var templateRoot: URL

    public init(templateRoot: URL) {
        self.templateRoot = templateRoot
    }

    public func render(_ domain: SyntheticDomain) throws -> [String: [String: Data]] {
        var output: [String: [String: Data]] = [:]
        let paths = try FileManager.default.subpathsOfDirectory(atPath: templateRoot.path).sorted()
        for path in paths where path.hasSuffix(".template") {
            let components = path.split(separator: "/").map(String.init)
            guard components.count >= 2 else { continue }
            let role = components[0]
            let relative = components.dropFirst().joined(separator: "/").replacingOccurrences(of: ".template", with: "")
            let template = try String(contentsOf: templateRoot.appending(path: path), encoding: .utf8)
            output["Domains/\(domain.name)/\(role)", default: [:]][substitute(relative, domain)] = Data(expand(template, for: domain).utf8)
        }
        return output
    }

    func expand(_ template: String, for domain: SyntheticDomain) -> String {
        var lines: [String] = []
        for line in template.split(separator: "\n", omittingEmptySubsequences: false).map(String.init) {
            if line.contains("__Dep__") || line.contains("__dep__") {
                for dependency in domain.dependsOn {
                    let value = dependency.prefix(1).lowercased() + dependency.dropFirst()
                    lines.append(substitute(line.replacingOccurrences(of: "__Dep__", with: dependency).replacingOccurrences(of: "__dep__", with: value), domain))
                }
            } else {
                lines.append(substitute(line, domain))
            }
        }
        return Self.sortImportBlocks(lines).joined(separator: "\n")
    }

    private func substitute(_ text: String, _ domain: SyntheticDomain) -> String {
        text.replacingOccurrences(of: "__Domain__", with: domain.name)
            .replacingOccurrences(of: "__domain__", with: domain.valueName)
            .replacingOccurrences(of: "__TITLE__", with: domain.title)
    }

    /// Keeps generated imports in the same alphabetical order as hand-written sources.
    static func sortImportBlocks(_ lines: [String]) -> [String] {
        func module(_ line: String) -> String? {
            line.wholeMatch(of: /(?:@testable\s+)?import\s+(\w+)\s*/).map { String($0.output.1).lowercased() }
        }
        var result: [String] = []
        var block: [String] = []
        for line in lines {
            if module(line) != nil {
                block.append(line)
                continue
            }
            result += block.sorted { module($0)! < module($1)! }
            block = []
            result.append(line)
        }
        return result + block.sorted { module($0)! < module($1)! }
    }
}

public enum SyntheticAppSource {
    /// The app file that registers synthetic domains and lists them in Explore. Emitted even when there are none.
    public static func render(_ domains: [SyntheticDomain]) -> String {
        let imports = (["DI", "SwiftUI"] + domains.map(\.name)).sorted { $0.lowercased() < $1.lowercased() }.map { "import \($0)" }
        let registrations = domains.map { "        \($0.name)Feature.register(in: container)" }
        let entries = domains.map { "        Entry(title: \($0.name)Feature.title) { AnyView(\($0.name)Feature.makeScreen(container: $0)) }," }
        let register = registrations.isEmpty
            ? "    static func register(in container: Container) {}"
            : "    static func register(in container: Container) {\n\(registrations.joined(separator: "\n"))\n    }"
        let list = entries.isEmpty
            ? "    static let entries: [Entry] = []"
            : "    static let entries: [Entry] = [\n\(entries.joined(separator: "\n"))\n    ]"
        return """
        // Generated by civitas-gen. Do not edit.
        \(imports.joined(separator: "\n"))

        /// Domains generated from the synthetic template, registered and listed by the app.
        @MainActor
        enum SyntheticFeatures {
            struct Entry {
                let title: String
                let screen: (Container) -> AnyView
            }

        \(register)

        \(list)
        }

        """
    }
}
